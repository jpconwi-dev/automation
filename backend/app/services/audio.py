"""Background music and sound effects, synthesised from scratch with numpy.

Nothing here ships or downloads a licensed track: the music loops and the effects are generated by code, so the
videos have no copyright strings attached. If you would rather use your own track, set MUSIC_PATH in backend/.env
(only use music you have the rights to) and it replaces the generated music.

build_soundtrack() returns one stereo WAV the length of the video: music (ducked under the narration) + effects.
The renderer mixes it with the narration.
"""
import subprocess
import wave
from functools import lru_cache
from pathlib import Path

import numpy as np

from ..core.config import settings
from ..core.errors import PipelineError
from .profiles import MUSIC_STYLES

SR = 44100
_rng = np.random.default_rng(7)  # fixed seed: the same style always sounds the same


# ----------------------------------------------------------------------------- helpers

def _hz(midi: float) -> float:
    return 440.0 * 2 ** ((midi - 69) / 12)


def _t(seconds: float) -> np.ndarray:
    return np.arange(int(seconds * SR)) / SR


def _put(buf: np.ndarray, start: float, sig: np.ndarray, gain: float = 1.0, pan: float = 0.0, wrap: bool = False) -> None:
    """Add a mono signal into a stereo buffer (2, N) at `start` seconds. wrap=True lets tails wrap around (loops)."""
    s0, n = int(round(start * SR)), buf.shape[1]
    l, r = gain * np.cos((pan + 1) * np.pi / 4), gain * np.sin((pan + 1) * np.pi / 4)
    if wrap:
        idx = (s0 + np.arange(len(sig))) % n
        np.add.at(buf[0], idx, (sig * l).astype(np.float32))
        np.add.at(buf[1], idx, (sig * r).astype(np.float32))
        return
    if s0 >= n or s0 + len(sig) <= 0:
        return
    a = max(0, -s0)
    b = min(len(sig), n - s0)
    seg = sig[a:b]
    buf[0, s0 + a:s0 + b] += seg * l
    buf[1, s0 + a:s0 + b] += seg * r


def _ads(n: int, attack: float, release: float) -> np.ndarray:
    """Soft attack/release envelope of n samples."""
    e = np.ones(n)
    a, r = min(n // 2, int(attack * SR)), min(n // 2, int(release * SR))
    if a:
        e[:a] = np.linspace(0, 1, a) ** 2
    if r:
        e[n - r:] = np.linspace(1, 0, r) ** 2
    return e


# ----------------------------------------------------------------------------- instruments (mono)

def _pluck(freq: float, dur: float, decay: float = 5.0) -> np.ndarray:
    t = _t(dur)
    s = (np.sin(2 * np.pi * freq * t) + 0.45 * np.sin(2 * np.pi * 2 * freq * t) * np.exp(-t * 7)
         + 0.2 * np.sin(2 * np.pi * 3 * freq * t) * np.exp(-t * 11))
    return s * np.exp(-t * decay) * np.minimum(1, t / 0.004)


def _marimba(freq: float, dur: float) -> np.ndarray:
    t = _t(dur)
    s = np.sin(2 * np.pi * freq * t) + 0.3 * np.sin(2 * np.pi * 4 * freq * t) * np.exp(-t * 30)
    return s * np.exp(-t * 9) * np.minimum(1, t / 0.003)


def _pad(freq: float, dur: float, attack: float = 0.7, release: float = 0.9) -> np.ndarray:
    t = _t(dur + release)
    s = np.zeros_like(t)
    for det, g in ((0.996, 0.5), (1.0, 0.8), (1.004, 0.5)):  # three slightly detuned voices = warm chorus
        ph = 2 * np.pi * freq * det * t
        s += g * (np.sin(ph) + 0.3 * np.sin(2 * ph) + 0.12 * np.sin(3 * ph))
    vib = 1 + 0.004 * np.sin(2 * np.pi * 4.8 * t)
    s *= vib
    env = np.ones_like(t)
    a, r = int(attack * SR), int(release * SR)
    env[:a] = np.linspace(0, 1, a) ** 2
    env[-r:] = np.linspace(1, 0, r) ** 2
    return s * env / 3


def _bass(freq: float, dur: float, punchy: bool = False) -> np.ndarray:
    t = _t(dur)
    s = np.sin(2 * np.pi * freq * t) + 0.25 * np.sin(4 * np.pi * freq * t)
    env = np.exp(-t * (6 if punchy else 1.6)) if punchy else _ads(len(t), 0.02, min(0.4, dur / 2))
    return s * env * np.minimum(1, t / 0.005)


def _kick(vol: float = 1.0) -> np.ndarray:
    t = _t(0.28)
    f = 48 + 90 * np.exp(-t * 28)
    ph = 2 * np.pi * np.cumsum(f) / SR
    return vol * np.sin(ph) * np.exp(-t * 14)


def _timpani() -> np.ndarray:
    t = _t(1.8)
    f = 62 + 30 * np.exp(-t * 14)
    ph = 2 * np.pi * np.cumsum(f) / SR
    return (np.sin(ph) + 0.4 * np.sin(1.5 * ph) * np.exp(-t * 6)) * np.exp(-t * 2.4)


def _hat(vol: float = 1.0, dur: float = 0.06) -> np.ndarray:
    t = _t(dur)
    n = np.diff(_rng.standard_normal(len(t) + 1))  # first difference = crude high-pass
    return vol * n * np.exp(-t * 75) * 0.5


def _clap() -> np.ndarray:
    t = _t(0.18)
    n = _rng.standard_normal(len(t))
    n = n - np.convolve(n, np.ones(8) / 8, mode="same")  # keep the mids and highs
    return n * np.exp(-t * 28) * 0.5


# ----------------------------------------------------------------------------- music loops

# chord = (root MIDI note, intervals)
_MAJ, _MIN, _MAJ7, _MIN7, _DOM = (0, 4, 7), (0, 3, 7), (0, 4, 7, 11), (0, 3, 7, 10), (0, 4, 7, 10)
C, D, E, F, G, A = 0, 2, 4, 5, 7, 9


def _ch(root: int, q: tuple, octave: int = 3) -> list[int]:
    base = 12 * (octave + 1) + root
    return [base + i for i in q]


STYLES = {
    # bpm, 8-bar progression, reverb amount
    "calm": dict(bpm=72, wet=0.34, prog=[(C, _MAJ7), (A, _MIN7), (F, _MAJ7), (G, _MAJ), (C, _MAJ7), (E, _MIN7), (F, _MAJ7), (G, _DOM)]),
    "upbeat": dict(bpm=112, wet=0.12, prog=[(C, _MAJ), (G, _MAJ), (A, _MIN), (F, _MAJ), (C, _MAJ), (G, _MAJ), (F, _MAJ), (G, _DOM)]),
    "cinematic": dict(bpm=64, wet=0.42, prog=[(A, _MIN), (F, _MAJ), (C, _MAJ), (G, _MAJ), (A, _MIN), (F, _MAJ), (D, _MIN), (E, _DOM)]),
    "playful": dict(bpm=100, wet=0.16, prog=[(C, _MAJ), (A, _MIN), (F, _MAJ), (G, _MAJ), (C, _MAJ), (A, _MIN), (D, _MIN7), (G, _DOM)]),
}
_PENTA = [0, 2, 4, 7, 9]  # major pentatonic degrees, used for melodies


def _melody_notes(chord: list[int], rng: np.random.Generator, count: int, lo: int, hi: int) -> list[int]:
    pool = [n for n in range(lo, hi + 1) if (n - chord[0]) % 12 in (0, 2, 4, 7, 9, 3, 10, 11) and (n % 12) in {0, 2, 4, 5, 7, 9, 11}]
    out, cur = [], int(rng.choice(pool))
    for _ in range(count):  # a gentle random walk sounds like a tune; random jumps do not
        step = int(rng.choice([-2, -1, -1, 0, 1, 1, 2]))
        i = max(0, min(len(pool) - 1, pool.index(min(pool, key=lambda p: abs(p - cur))) + step))
        cur = pool[i]
        out.append(cur)
    return out


def _reverb_circular(x: np.ndarray, wet: float, seconds: float = 2.2) -> np.ndarray:
    """Circular convolution with a decaying-noise impulse response, so the loop's reverb tail wraps seamlessly."""
    n = x.shape[1]
    m = min(int(seconds * SR), n)
    t = np.arange(m) / SR
    out = np.empty_like(x)
    rng = np.random.default_rng(11)
    for ch in range(2):
        ir = rng.standard_normal(m) * np.exp(-t * 3.2)
        ir[: int(0.012 * SR)] *= np.linspace(0, 1, int(0.012 * SR))
        ir /= np.sqrt(np.sum(ir ** 2)) + 1e-9
        wetsig = np.fft.irfft(np.fft.rfft(x[ch].astype(np.float64)) * np.fft.rfft(ir, n), n)
        out[ch] = ((1 - wet * 0.6) * x[ch] + wet * 1.1 * wetsig).astype(np.float32)
    return out


@lru_cache(maxsize=8)
def _music_loop(style: str) -> np.ndarray:
    """A seamless 16-bar loop (stereo float32, RMS-normalised). The second 8 bars add a melody for variety."""
    cfg = STYLES[style]
    beat = 60.0 / cfg["bpm"]
    bar = 4 * beat
    bars = 16
    n = int(bars * bar * SR)
    buf = np.zeros((2, n), dtype=np.float32)
    rng = np.random.default_rng({"calm": 1, "upbeat": 2, "cinematic": 3, "playful": 4}[style])

    for b in range(bars):
        root, q = cfg["prog"][b % 8]
        t0 = b * bar
        second = b >= 8
        tones = _ch(root, q, 3)
        high = _ch(root, q, 4)
        if style == "calm":
            for i, nt in enumerate(tones):
                _put(buf, t0, _pad(_hz(nt), bar), 0.30, pan=-0.35 + 0.23 * i, wrap=True)
            _put(buf, t0, _bass(_hz(tones[0] - 12), bar), 0.42, wrap=True)
            arp = high + [high[1] + 12, high[2] + 12] if len(high) == 3 else high + [high[0] + 12, high[1] + 12]
            seq = [0, 1, 2, 3, 2, 1, 3, 1]
            for k in range(8):
                _put(buf, t0 + k * beat / 2, _pluck(_hz(arp[seq[k] % len(arp)] + 12), 1.2, 4.5), 0.16, pan=(-0.5 if k % 2 else 0.5), wrap=True)
            if second:
                for k, nt in enumerate(_melody_notes(high, rng, 4, 72, 88)):
                    _put(buf, t0 + k * beat, _pluck(_hz(nt), 2.0, 2.4), 0.20, pan=0.1, wrap=True)
        elif style == "upbeat":
            for k in range(4):  # four-on-the-floor, gentle
                _put(buf, t0 + k * beat, _kick(0.55), 0.5, wrap=True)
            for k in range(8):
                _put(buf, t0 + k * beat / 2, _hat(1.0 if k % 2 else 0.5), 0.22, pan=0.3, wrap=True)
            for k in (1, 3):
                _put(buf, t0 + k * beat, _clap(), 0.18, wrap=True)
            for k in range(8):  # pumping bass on the off-beats
                if k % 2:
                    _put(buf, t0 + k * beat / 2, _bass(_hz(tones[0] - 12), beat / 2, punchy=True), 0.40, wrap=True)
            for k in (0.5, 1.5, 2.5, 3.5):  # chord stabs on the "and"
                for nt in high:
                    _put(buf, t0 + k * beat, _pluck(_hz(nt), 0.5, 9), 0.09, pan=-0.2, wrap=True)
            if second:
                for k, nt in enumerate(_melody_notes(high, rng, 8, 72, 91)):
                    _put(buf, t0 + k * beat / 2, _pluck(_hz(nt), 0.6, 6), 0.15, pan=0.25, wrap=True)
        elif style == "cinematic":
            for i, nt in enumerate(tones + [tones[0] + 12]):
                _put(buf, t0, _pad(_hz(nt - 12 if i == 0 else nt), bar, 1.4, 1.6), 0.28, pan=-0.5 + 0.3 * i, wrap=True)
            _put(buf, t0, _bass(_hz(tones[0] - 24), bar), 0.55, wrap=True)
            if b % 2 == 0:
                _put(buf, t0, _timpani(), 0.5, wrap=True)
            for k in range(4):
                _put(buf, t0 + k * beat + beat / 2, _pluck(_hz(high[k % len(high)] + 24), 2.0, 3.0), 0.07, pan=(-0.6 if k % 2 else 0.6), wrap=True)
            if second:
                for k, nt in enumerate(_melody_notes(high, rng, 2, 69, 84)):
                    _put(buf, t0 + k * 2 * beat, _pad(_hz(nt), 2 * beat, 0.5, 0.8), 0.22, pan=0.2, wrap=True)
        else:  # playful
            for k in (0, 2):
                _put(buf, t0 + k * beat, _bass(_hz(tones[0] - 12), beat * 0.7, punchy=True), 0.42, wrap=True)
            for k in (1, 3):
                for nt in high:
                    _put(buf, t0 + k * beat, _marimba(_hz(nt), 0.7), 0.10, pan=-0.2, wrap=True)
            for k in range(8):
                _put(buf, t0 + k * beat / 2, _hat(0.7, 0.04), 0.14, pan=0.4, wrap=True)
            notes = _melody_notes(high, rng, 8, 72, 91)
            for k, nt in enumerate(notes):
                if second or k % 2 == 0:
                    _put(buf, t0 + k * beat / 2, _marimba(_hz(nt), 0.8), 0.20, pan=0.15, wrap=True)

    buf = _reverb_circular(buf, cfg["wet"])
    rms = float(np.sqrt(np.mean(buf.astype(np.float64) ** 2))) + 1e-9
    return (buf * (0.115 / rms)).astype(np.float32)  # about -19 dBFS RMS before ducking


# ----------------------------------------------------------------------------- sound effects (stereo)

def _stereo(mono: np.ndarray, pan: np.ndarray | float = 0.0) -> np.ndarray:
    p = np.broadcast_to(np.asarray(pan, dtype=np.float64), mono.shape)
    return np.stack([mono * np.cos((p + 1) * np.pi / 4), mono * np.sin((p + 1) * np.pi / 4)]).astype(np.float32)


@lru_cache(maxsize=None)
def _sfx_whoosh() -> np.ndarray:
    n = int(0.85 * SR)
    t = np.arange(n) / n
    x = np.random.default_rng(3).standard_normal(n)
    cutoff = 250 + 3600 * np.sin(np.pi * np.clip(t * 1.15, 0, 1)) ** 2  # sweeps up then down
    a = 1 - np.exp(-2 * np.pi * cutoff / SR)
    y, last = np.empty(n), 0.0
    for i in range(n):
        last += a[i] * (x[i] - last)
        y[i] = last
    env = np.sin(np.pi * t) ** 1.6
    y = y * env
    y /= np.max(np.abs(y)) + 1e-9
    return _stereo(y * 0.9, -0.8 + 1.6 * t)  # travels left to right


@lru_cache(maxsize=None)
def _sfx_pop() -> np.ndarray:
    t = _t(0.16)
    f = 520 * np.exp(t * 8.5)
    s = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 32)
    return _stereo(s * 0.9)


@lru_cache(maxsize=None)
def _sfx_sparkle() -> np.ndarray:
    out = np.zeros(int(1.4 * SR))
    for i, midi in enumerate((84, 88, 91, 96)):
        t = _t(1.0)
        s = (np.sin(2 * np.pi * _hz(midi) * t) + 0.3 * np.sin(2 * np.pi * _hz(midi) * 2.01 * t)) * np.exp(-t * 6.5)
        o = int(i * 0.075 * SR)
        out[o:o + len(s)] += s[: len(out) - o] * (0.6 + 0.1 * i)
    return _stereo(out / (np.max(np.abs(out)) + 1e-9) * 0.8)


@lru_cache(maxsize=None)
def _sfx_chime() -> np.ndarray:
    out = np.zeros(int(2.8 * SR))
    for k, (midi, delay) in enumerate(((76, 0.0), (83, 0.16), (88, 0.32))):
        t = _t(2.4)
        s = sum(g * np.sin(2 * np.pi * _hz(midi) * r * t) * np.exp(-t * d)
                for r, g, d in ((1, 1.0, 1.8), (2.76, 0.35, 3.2), (5.4, 0.15, 5.5), (8.93, 0.06, 8.0)))
        o = int(delay * SR)
        out[o:o + len(s)] += s[: len(out) - o] * (0.9 - 0.15 * k)
    return _stereo(out / (np.max(np.abs(out)) + 1e-9) * 0.8)


# ----------------------------------------------------------------------------- external music

def _load_external(path: Path, tmp: Path) -> np.ndarray:
    dst = tmp / "music_ext.wav"
    r = subprocess.run([settings.ffmpeg_path, "-y", "-hide_banner", "-i", str(path), "-ar", str(SR), "-ac", "2",
                        "-c:a", "pcm_s16le", str(dst)], capture_output=True, text=True, timeout=300)
    if r.returncode != 0 or not dst.is_file():
        raise PipelineError(f"Couldn't read MUSIC_PATH ({path.name}): {r.stderr[-300:]}")
    with wave.open(str(dst), "rb") as w:
        raw = np.frombuffer(w.readframes(w.getnframes()), dtype="<i2").astype(np.float32) / 32768
    if raw.size < SR:
        raise PipelineError("The file in MUSIC_PATH is shorter than one second.")
    x = raw.reshape(-1, 2).T.copy()
    x *= 0.115 / (float(np.sqrt(np.mean(x.astype(np.float64) ** 2))) + 1e-9)
    return x


# ----------------------------------------------------------------------------- the mix

def _duck_envelope(total: float, n: int, speech_spans: list[tuple[float, float]], depth: float) -> np.ndarray:
    """Music gain over time: `depth` while someone is speaking, 1.0 in the gaps, with smooth ramps."""
    rate = 100
    ctrl = np.ones(int(total * rate) + 2, dtype=np.float32)
    for a, b in speech_spans:
        ctrl[int(max(0, a - 0.1) * rate): int((b + 0.25) * rate) + 1] = depth
    k = np.hanning(41)  # about 0.4 s smoothing
    ctrl = np.convolve(ctrl, k / k.sum(), mode="same")
    return np.interp(np.arange(n) / SR, np.arange(len(ctrl)) / rate, ctrl).astype(np.float32)


def build_soundtrack(*, total: float, starts: list[float], speech: list[float], style: str, music: bool, sfx: bool,
                     tmp: Path, out_path: Path) -> Path | None:
    """Write music + effects as a stereo 16-bit WAV of exactly `total` seconds. Returns None if both are off."""
    if not (music or sfx):
        return None
    n = int(round(total * SR))
    mix = np.zeros((2, n), dtype=np.float32)

    if music:
        ext = Path(settings.music_path) if settings.music_path else None
        if ext and ext.is_file():
            loop = _load_external(ext, tmp)
        else:
            loop = _music_loop(style if style in MUSIC_STYLES else "calm")
        reps = int(np.ceil(n / loop.shape[1]))
        bed = np.tile(loop, (1, reps))[:, :n]
        spans = [(s, s + sp) for s, sp in zip(starts, speech)]
        bed = bed * _duck_envelope(total, n, spans, depth=0.42)[None, :]
        fade_in, fade_out = min(1.5, total / 4), min(2.5, total / 4)
        g = np.ones(n, dtype=np.float32)
        a, b = int(fade_in * SR), int(fade_out * SR)
        g[:a] = np.linspace(0, 1, a)
        g[n - b:] = np.linspace(1, 0, b)
        mix += bed * g[None, :] * float(settings.music_level)

    if sfx:
        lvl = float(settings.sfx_level)

        def add(t: float, snd: np.ndarray, gain: float) -> None:
            s0 = int(round(t * SR))
            if s0 >= n:
                return
            seg = snd[:, : n - s0]
            mix[:, s0:s0 + seg.shape[1]] += seg * gain * lvl

        add(0.05, _sfx_sparkle(), 0.30)
        for k in range(1, len(starts)):
            add(max(0.0, starts[k] - 0.35), _sfx_whoosh(), 0.22)   # transition whoosh into each new scene
            add(starts[k] + 0.30, _sfx_pop(), 0.20)                  # caption "pop" as the on-screen text appears
        add(starts[0] + 0.30, _sfx_pop(), 0.20)
        end_t = starts[-1] + speech[-1] + 0.2
        add(min(end_t, max(0.0, total - 2.0)), _sfx_chime(), 0.30)   # closing chime after the last word

    np.clip(mix, -0.98, 0.98, out=mix)
    pcm = (mix.T * 32767).astype("<i2")
    with wave.open(str(out_path), "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())
    return out_path
